#!/usr/bin/env node
/**
 * Materialise the canonical contract corpus into `typescript/_schemas` as a
 * REAL directory, because npm does **not** dereference the repo-root `schemas/`
 * symlink into the packed artifact (verified: `npm pack` shipped 0 files).
 *
 * The source of truth stays `<repo>/schemas`; this copy is generated (and
 * gitignored). Run from npm `prepack`/`build` and the pack gate. Mirrors what
 * `cargo package` does for the Rust `rigorix-schemas` crate (SDK-C6-PACKAGING).
 */
import {
  cpSync,
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url)); // typescript/scripts
const packageRoot = join(here, ".."); // typescript/
const repoRoot = join(packageRoot, ".."); // repo root
const source = join(repoRoot, "schemas");
const target = join(packageRoot, "_schemas");

if (!existsSync(source)) {
  console.error(`bundle-schemas: canonical corpus not found at ${source}`);
  process.exit(1);
}

// Replace a stale symlink or copy with a real directory.
rmSync(target, { recursive: true, force: true });
mkdirSync(target, { recursive: true });
cpSync(source, target, { recursive: true, dereference: true });

function count(dir) {
  return readdirSync(dir, { withFileTypes: true }).reduce(
    (total, entry) =>
      total + (entry.isDirectory() ? count(join(dir, entry.name)) : 1),
    0,
  );
}

console.log(
  `bundle-schemas: ${count(target)} files -> ${relative(packageRoot, target)}`,
);

// The browser entry cannot read the filesystem, so emit the canonical schemas
// (fixtures excluded) as string constants. This file is gitignored and rebuilt
// by `npm run bundle` (which `build` and `prepack` run).
const browserDir = join(packageRoot, "src", "browser");
mkdirSync(browserDir, { recursive: true });

const schemas = {};
function collect(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    const rel = relative(target, full).split("\\").join("/");
    if (entry.isDirectory()) {
      if (rel === "fixtures" || rel.startsWith("fixtures/")) continue;
      collect(full);
    } else if (entry.name.endsWith(".json")) {
      schemas[rel] = readFileSync(full, "utf8");
    }
  }
}
collect(target);

const ordered = Object.fromEntries(
  Object.entries(schemas).sort(([a], [b]) => a.localeCompare(b)),
);
const generated = `// AUTO-GENERATED by scripts/bundle-schemas.mjs — do not edit.\n// The browser entry has no fs; the canonical schemas are string constants.\nexport const SCHEMAS: Record<string, string> = ${JSON.stringify(ordered, null, 2)};\n`;
writeFileSync(join(browserDir, "corpus.generated.ts"), generated);
console.log(
  `bundle-schemas: ${Object.keys(ordered).length} schemas -> src/browser/corpus.generated.ts`,
);
