//! Canonical Rigorix contracts as a consumable crate.
//!
//! @canonical schemas/README.md — the contract corpus this crate embeds
//! (strategy freeze D-1: `schemas/` is the single source of truth; D-2:
//! schemas + verifiers). ADR-0001 freezes the `rigorix.*` catalog within it.
//!
//! This crate embeds the entire [`schemas/`] corpus — the JSON Schemas
//! (`envelope.json`, `claims.json`, `policy.json`, `api/*.json`, …) **and** the
//! conformance fixture corpus (`fixtures/**`) — at build time, and exposes it
//! by relative path. It is the distributable form of the single source of
//! truth (strategy freeze D-1/D-2), consumed by `rigorix-verifier`, the
//! Python/TypeScript verifiers, and both servers — one copy, no vendoring.
//!
//! The crate is data + lookup: no engine dependency, no runtime filesystem
//! access. The embedded table is generated by `build.rs` from the repo-root
//! `schemas/` (a symlink to it lives in this crate so `cargo package` ships the
//! dereferenced corpus); a sync test fails if the embedded set diverges from
//! the on-disk contract.
//!
//! ```no_run
//! use rigorix_schemas::{fixture, schema, schema_by_id};
//!
//! let envelope = schema("envelope.json").expect("envelope schema");
//! let chain = fixture("integrity/chain.json").expect("integrity fixture");
//! let id = schema_by_id("https://rigorix.eu/schemas/envelope-v2.json");
//! assert_eq!(id, Some("envelope.json"));
//! # let _ = (envelope, chain);
//! ```

include!(concat!(env!("OUT_DIR"), "/embedded.rs"));

/// Return the embedded contract at `rel_path`, relative to `schemas/`
/// (e.g. `"envelope.json"`, `"api/catalog.json"`,
/// `"fixtures/integrity/chain.json"`).
pub fn schema(rel_path: &str) -> Option<&'static str> {
    FILES
        .binary_search_by(|(path, _)| (*path).cmp(rel_path))
        .ok()
        .map(|index| FILES[index].1)
}

/// Every embedded path, sorted (`NAMES[i]` corresponds to `FILES[i].0`).
pub fn schema_names() -> &'static [&'static str] {
    NAMES
}

/// Return the embedded conformance fixture at `rel_path`, relative to
/// `fixtures/` (e.g. `"integrity/chain.json"`, `"envelope/envelope-rich-signed.json"`).
///
/// Equivalent to `schema(&format!("fixtures/{rel_path}"))`.
pub fn fixture(rel_path: &str) -> Option<&'static str> {
    let mut key = String::with_capacity("fixtures/".len() + rel_path.len());
    key.push_str("fixtures/");
    key.push_str(rel_path);
    schema(&key)
}

/// Resolve a schema `$id` (e.g. `https://rigorix.eu/schemas/envelope-v2.json`)
/// to its embedded path — for registering cross-file `$ref` resources.
pub fn schema_by_id(id: &str) -> Option<&'static str> {
    IDS.iter()
        .find(|(schema_id, _)| *schema_id == id)
        .map(|(_, path)| *path)
}

/// The `$id -> path` map exposed by the corpus.
pub fn schema_ids() -> &'static [(&'static str, &'static str)] {
    IDS
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::BTreeMap;
    use std::path::{Path, PathBuf};

    /// The canonical on-disk corpus: prefer the repo-root `schemas/` (the
    /// single source of truth); fall back to the in-crate symlink.
    fn disk_root() -> PathBuf {
        let manifest = Path::new(env!("CARGO_MANIFEST_DIR"));
        let repo_root = manifest.join("../../schemas");
        if repo_root.is_dir() {
            repo_root
        } else {
            manifest.join("schemas")
        }
    }

    fn walk(root: &Path, dir: &Path, out: &mut BTreeMap<String, Vec<u8>>) {
        for entry in std::fs::read_dir(dir).expect("read schemas dir") {
            let path = entry.expect("dir entry").path();
            if path.is_dir() {
                walk(root, &path, out);
            } else {
                let rel = path
                    .strip_prefix(root)
                    .expect("path under schemas root")
                    .to_string_lossy()
                    .replace('\\', "/");
                out.insert(rel, std::fs::read(&path).expect("read schema file"));
            }
        }
    }

    #[test]
    fn embedded_corpus_matches_disk() {
        let root = disk_root();
        let mut on_disk = BTreeMap::new();
        walk(&root, &root, &mut on_disk);

        assert!(
            on_disk.len() >= 25,
            "expected the frozen corpus (>= 25 files), found {} under {}",
            on_disk.len(),
            root.display()
        );
        assert!(
            on_disk.contains_key("fixtures/integrity/chain.json"),
            "the ADR-016 integrity fixtures must be part of the corpus"
        );

        let mut seen = std::collections::HashSet::new();
        for (path, _) in FILES {
            assert!(seen.insert(*path), "duplicate embedded path `{path}`");
        }
        assert_eq!(schema_names().len(), FILES.len());

        // Every on-disk file is embedded, byte-equal.
        for (rel, bytes) in &on_disk {
            let embedded =
                schema(rel).unwrap_or_else(|| panic!("`{rel}` is not embedded in the crate"));
            assert_eq!(
                embedded.as_bytes(),
                bytes.as_slice(),
                "embedded `{rel}` diverges from the on-disk contract"
            );
        }
        // No extra embedded files.
        for (rel, _) in FILES {
            assert!(
                on_disk.contains_key(*rel),
                "embedded `{rel}` is not present on disk"
            );
        }
    }

    #[test]
    fn exposes_schemas_fixtures_and_ids() {
        assert!(schema("envelope.json").is_some());
        assert!(schema("api/catalog.json").is_some());
        assert!(schema("fixtures/integrity/chain.json").is_some());

        // `fixture()` is relative to `fixtures/`.
        assert!(fixture("integrity/chain.json").is_some());
        assert!(fixture("envelope/envelope-rich-signed.json").is_some());
        assert!(fixture("does/not/exist.json").is_none());

        assert_eq!(
            schema_by_id("https://rigorix.eu/schemas/envelope-v2.json"),
            Some("envelope.json")
        );
        assert_eq!(
            schema_by_id("https://rigorix.eu/schemas/claims.json"),
            Some("claims.json")
        );
        assert!(schema_ids()
            .iter()
            .any(|(id, path)| id.ends_with("/envelope-v2.json") && *path == "envelope.json"));
    }
}
