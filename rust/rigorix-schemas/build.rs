//! Build-time embedding of the canonical contract corpus.
//!
//! `schemas/` inside this crate is a **symlink to the repo-root `schemas/`**
//! (the single source of truth). `cargo package` dereferences the symlink into
//! the published crate, so this script walks the same relative path in both
//! the repo and the package — no committed duplicate, no runtime file access.
//!
//! It emits `$OUT_DIR/embedded.rs` with three statics:
//! - `FILES: &[(&str, &str)]` — `(path relative to schemas/, contents)`
//! - `NAMES: &[&str]` — every path, sorted
//! - `IDS: &[(&str, &str)]` — `$id -> path` for schemas that declare one

use std::path::{Path, PathBuf};
use std::{env, fs};

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let root = manifest.join("schemas");
    if !root.is_dir() {
        panic!(
            "rigorix-schemas: expected the canonical contract corpus at {} \
             (the `schemas` symlink is missing or dangling)",
            root.display()
        );
    }
    // Re-run when the corpus changes (the dir and each file below).
    println!("cargo:rerun-if-changed={}", root.display());

    let mut rels: Vec<String> = Vec::new();
    collect(&root, &root, &mut rels);
    rels.sort();
    if rels.is_empty() {
        panic!("rigorix-schemas: no files found under {}", root.display());
    }

    let mut files = String::new();
    let mut names = String::new();
    let mut ids = String::new();
    for rel in &rels {
        let abs = root.join(rel);
        println!("cargo:rerun-if-changed={}", abs.display());
        // `concat!` keeps the path relative to the build root (works in-repo
        // via the symlink and in the packaged crate).
        files.push_str(&format!(
            "({rel:?}, include_str!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/schemas/{rel}\"))),\n"
        ));
        names.push_str(&format!("{rel:?},\n"));
        if rel.ends_with(".json") {
            if let Ok(text) = fs::read_to_string(&abs) {
                if let Ok(value) = serde_json::from_str::<serde_json::Value>(&text) {
                    if let Some(id) = value.get("$id").and_then(|v| v.as_str()) {
                        ids.push_str(&format!("({id:?}, {rel:?}),\n"));
                    }
                }
            }
        }
    }

    let generated = format!(
        "// @generated by build.rs from the `schemas/` corpus — do not edit.\n\
         /// Every embedded file: `(path relative to schemas/, contents)`.\n\
         pub static FILES: &[(&str, &str)] = &[\n{files}];\n\n\
         /// Every embedded path, sorted (same order as [`FILES`]).\n\
         pub static NAMES: &[&str] = &[\n{names}];\n\n\
         /// `$id` -> path for every schema that declares an `$id`.\n\
         pub static IDS: &[(&str, &str)] = &[\n{ids}];\n"
    );
    let out = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR")).join("embedded.rs");
    fs::write(&out, generated).expect("write embedded.rs");
}

fn collect(root: &Path, dir: &Path, out: &mut Vec<String>) {
    for entry in fs::read_dir(dir).expect("read schemas directory") {
        let path = entry.expect("schema dir entry").path();
        if path.is_dir() {
            collect(root, &path, out);
        } else {
            let rel = path.strip_prefix(root).expect("path under schemas root");
            out.push(rel.to_string_lossy().replace('\\', "/"));
        }
    }
}
