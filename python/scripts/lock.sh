#!/usr/bin/env bash
# lock.sh — regenerate python/requirements.lock from pyproject.toml.
#
# The lockfile is what a licence audit reads, so the graph that is audited is the
# graph that ships. It runs in the same Linux image the tests use, so a macOS-only
# resolvable wheel cannot enter the lock.
#
# Usage: bash python/scripts/lock.sh
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

docker run --rm -v "$ROOT:/repo" -w /repo python:3.12-slim sh -c '
  set -e
  pip install -q --upgrade pip >/dev/null 2>&1
  # Install the package itself so the resolution is the published one.
  pip install -q . >/dev/null 2>&1
  {
    echo "# Generated by python/scripts/lock.sh — do not edit by hand."
    echo "# Runtime dependency graph of rigorix-verifier (Linux, CPython 3.12)."
    echo "# Regenerate after changing pyproject.toml; licence audit reads this file."
    pip freeze --exclude rigorix-verifier
  }
' > "$ROOT/requirements.lock"
echo "wrote python/requirements.lock ($(grep -c . "$ROOT/requirements.lock") lines)"
